import { readFile, writeFile, rename } from 'node:fs/promises';

// A snapshot reserves historical URLs; it does not copy content or media.
const target = new URL('../functions/_news-archive.ts', import.meta.url);
let rows;
if (process.argv.includes('--from-stdin')) {
  const envelope = JSON.parse(await readFile('/dev/stdin', 'utf8'));
  const data = envelope.data?.result ?? envelope;
  rows = data.rows;
  if (rows?.length !== data.total) throw new Error('Incomplete archive snapshot');
} else {
  rows = [];
  let pages = 1;
  let total = 0;
  for (let page = 1; page <= pages; page++) {
    const response = await fetch(`https://www.crf-al.org.br/wp-json/wp/v2/posts?per_page=100&page=${page}&_fields=id,slug,date,date_gmt,modified`, { signal: AbortSignal.timeout(15000) });
    if (!response.ok) throw new Error(`Archive HTTP ${response.status}`);
    pages = Number(response.headers.get('x-wp-totalpages'));
    total = Number(response.headers.get('x-wp-total'));
    if (!Number.isInteger(pages) || pages < 1 || pages > 100) throw new Error('Invalid page count');
    rows.push(...await response.json());
  }
  if (rows.length !== total) throw new Error('Archive changed during snapshot; retry');
}
if (!Array.isArray(rows) || !rows.length) throw new Error('Empty archive');
const slugs = new Set();
const ids = new Set();
for (const row of rows) {
  if (!Number.isSafeInteger(row.id) || row.id < 1 || !row.slug || /[/?#]/.test(row.slug) || !Number.isFinite(Date.parse(row.date_gmt + 'Z')) || ids.has(row.id) || slugs.has(row.slug)) throw new Error('Invalid or duplicate archive entry');
  ids.add(row.id); slugs.add(row.slug);
}
const source = `// Generated by scripts/generate-news-archive.mjs. Refresh before editorial cutover.\nexport const NEWS_ARCHIVE: Array<{id: number; slug: string; date: string; date_gmt: string; modified: string}> = ${JSON.stringify(rows)};\n`;
const temporary = new URL('../functions/_news-archive.ts.tmp', import.meta.url);
await writeFile(temporary, source);
await rename(temporary, target);
console.log(`Reserved ${rows.length} historical news URLs.`);
